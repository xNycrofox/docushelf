#!/bin/sh
# Entry point of the DocuShelf FTP container.
#
# Creates the upload account, writes vsftpd.conf from the environment and
# runs vsftpd in the foreground. There is exactly one account; it is chrooted
# to the upload directory and may only upload: no downloads, no deletes, no
# anonymous access, passive mode only.
#
# Environment
#   FTP_USER            account name (default: scanner)
#   FTP_PASSWORD        password; or FTP_PASSWORD_FILE with a file containing it
#   FTP_UID, FTP_GID    owner of uploaded files (default 1000:1000 = DocuShelf)
#   FTP_UMASK           umask for uploads (default 027: files 0640, folders 0750)
#   FTP_PASV_ADDRESS    address announced for passive mode: the IP the scanner
#                       connects to (empty: the container's own address)
#   FTP_PASV_MIN_PORT, FTP_PASV_MAX_PORT   passive port range (default 30000-30009)
#   FTP_HIDE_FILES      yes (default): directory listings stay empty, so the
#                       account cannot see what is waiting in the drop zone
#   FTP_MAX_CLIENTS     simultaneous connections (default 10)
#   FTP_TLS_CERT, FTP_TLS_KEY   certificate and key for optional FTPS
#                       (default /certs/tls.crt and /certs/tls.key, used if present)
#   FTP_TLS_REQUIRED    yes: logins and transfers only with TLS (default no)
#
# "docushelf-ftp --print-config" prints the generated configuration and exits.
set -eu

UPLOAD_DIR=/srv/ftp
CONFIG=/etc/vsftpd/vsftpd.conf
USER_LIST=/etc/vsftpd/user_list

log() { echo "docushelf-ftp: $*"; }
fail() {
    echo "docushelf-ftp: $*" >&2
    exit 1
}

is_number() {
    case "$1" in '' | *[!0-9]*) return 1 ;; *) return 0 ;; esac
}

is_yes() {
    case "$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')" in 1 | yes | ja | true | on) return 0 ;; *) return 1 ;; esac
}

FTP_USER="${FTP_USER:-scanner}"
FTP_UID="${FTP_UID:-1000}"
FTP_GID="${FTP_GID:-1000}"
FTP_UMASK="${FTP_UMASK:-027}"
FTP_PASV_ADDRESS="${FTP_PASV_ADDRESS:-}"
FTP_PASV_MIN_PORT="${FTP_PASV_MIN_PORT:-30000}"
FTP_PASV_MAX_PORT="${FTP_PASV_MAX_PORT:-30009}"
FTP_HIDE_FILES="${FTP_HIDE_FILES:-yes}"
FTP_MAX_CLIENTS="${FTP_MAX_CLIENTS:-10}"
FTP_TLS_CERT="${FTP_TLS_CERT:-/certs/tls.crt}"
FTP_TLS_KEY="${FTP_TLS_KEY:-/certs/tls.key}"
FTP_TLS_REQUIRED="${FTP_TLS_REQUIRED:-no}"

validate() {
    case "$FTP_USER" in
        '' | *[!a-z0-9_-]* | [0-9_-]*) fail "FTP_USER '$FTP_USER' ist ungültig (Kleinbuchstaben, Ziffern, - und _)" ;;
    esac
    [ "$FTP_USER" != "root" ] || fail "FTP_USER darf nicht root sein"
    is_number "$FTP_UID" || fail "FTP_UID muss eine Zahl sein"
    is_number "$FTP_GID" || fail "FTP_GID muss eine Zahl sein"
    [ "$FTP_UID" -gt 0 ] || fail "FTP_UID darf nicht 0 (root) sein"
    case "$FTP_UMASK" in [0-7][0-7][0-7] | 0[0-7][0-7][0-7]) ;; *) fail "FTP_UMASK muss ein Oktalwert sein, z. B. 027" ;; esac
    is_number "$FTP_PASV_MIN_PORT" || fail "FTP_PASV_MIN_PORT muss eine Zahl sein"
    is_number "$FTP_PASV_MAX_PORT" || fail "FTP_PASV_MAX_PORT muss eine Zahl sein"
    [ "$FTP_PASV_MIN_PORT" -ge 1024 ] && [ "$FTP_PASV_MAX_PORT" -le 65535 ] &&
        [ "$FTP_PASV_MIN_PORT" -le "$FTP_PASV_MAX_PORT" ] ||
        fail "Passive Ports $FTP_PASV_MIN_PORT-$FTP_PASV_MAX_PORT: erwartet 1024 <= MIN <= MAX <= 65535"
    is_number "$FTP_MAX_CLIENTS" && [ "$FTP_MAX_CLIENTS" -gt 0 ] || fail "FTP_MAX_CLIENTS muss eine Zahl > 0 sein"
    case "$FTP_PASV_ADDRESS" in *[!A-Za-z0-9.:-]*) fail "FTP_PASV_ADDRESS '$FTP_PASV_ADDRESS' ist ungültig" ;; esac
    if is_yes "$FTP_TLS_REQUIRED" && ! tls_available; then
        fail "FTP_TLS_REQUIRED ist gesetzt, aber $FTP_TLS_CERT oder $FTP_TLS_KEY fehlt"
    fi
}

tls_available() {
    [ -r "$FTP_TLS_CERT" ] && [ -r "$FTP_TLS_KEY" ]
}

read_password() {
    if [ -n "${FTP_PASSWORD_FILE:-}" ]; then
        [ -r "$FTP_PASSWORD_FILE" ] || fail "FTP_PASSWORD_FILE $FTP_PASSWORD_FILE ist nicht lesbar"
        FTP_PASSWORD="$(cat "$FTP_PASSWORD_FILE")"
    fi
    [ -n "${FTP_PASSWORD:-}" ] || fail "FTP_PASSWORD fehlt (oder FTP_PASSWORD_FILE setzen)"
    [ "${#FTP_PASSWORD}" -ge 8 ] || fail "FTP_PASSWORD ist zu kurz (mindestens 8 Zeichen)"
    case "$FTP_PASSWORD" in *"
"*) fail "FTP_PASSWORD darf keinen Zeilenumbruch enthalten" ;; esac
}

write_config() {
    target="$1"
    if is_yes "$FTP_TLS_REQUIRED"; then tls_force=YES; else tls_force=NO; fi
    {
        echo "# Generated by docushelf-ftp at container start; changes are overwritten."
        echo "listen=YES"
        echo "listen_ipv6=NO"
        echo "listen_port=21"
        echo "background=NO"
        echo "max_clients=$FTP_MAX_CLIENTS"
        echo "max_per_ip=$FTP_MAX_CLIENTS"
        echo "idle_session_timeout=300"
        echo "data_connection_timeout=120"
        echo "ftpd_banner=DocuShelf Scan-Eingang"
        echo
        echo "# Accounts: only the upload account, never anonymous"
        echo "anonymous_enable=NO"
        echo "local_enable=YES"
        echo "userlist_enable=YES"
        echo "userlist_deny=NO"
        echo "userlist_file=$USER_LIST"
        echo "check_shell=NO"
        echo "pam_service_name=vsftpd"
        echo "chroot_local_user=YES"
        echo "allow_writeable_chroot=YES"
        echo "passwd_chroot_enable=NO"
        echo "local_root=$UPLOAD_DIR"
        echo "hide_ids=YES"
        echo
        echo "# Upload only: no downloads, no deletes, no permission changes"
        echo "write_enable=YES"
        echo "download_enable=NO"
        echo "chmod_enable=NO"
        echo "cmds_denied=DELE,RMD,SITE"
        echo "delete_failed_uploads=YES"
        echo "local_umask=$FTP_UMASK"
        echo "file_open_mode=0666"
        echo "dirlist_enable=YES"
        if is_yes "$FTP_HIDE_FILES"; then
            echo "hide_file={*}"
        fi
        echo
        echo "# Passive mode only; active mode cannot work through the container network"
        echo "pasv_enable=YES"
        echo "pasv_min_port=$FTP_PASV_MIN_PORT"
        echo "pasv_max_port=$FTP_PASV_MAX_PORT"
        if [ -n "$FTP_PASV_ADDRESS" ]; then
            echo "pasv_address=$FTP_PASV_ADDRESS"
            case "$FTP_PASV_ADDRESS" in
                *[!0-9.]*) echo "pasv_addr_resolve=YES" ;;
                *) echo "pasv_addr_resolve=NO" ;;
            esac
        fi
        echo "port_enable=NO"
        echo "connect_from_port_20=NO"
        echo
        echo "# The seccomp and namespace sandboxes need privileges a container does not have"
        echo "seccomp_sandbox=NO"
        echo "isolate=NO"
        echo "isolate_network=NO"
        echo "secure_chroot_dir=/var/lib/vsftpd/empty"
        echo
        echo "# Log logins and uploads to the container log"
        echo "syslog_enable=NO"
        echo "xferlog_enable=YES"
        echo "xferlog_std_format=NO"
        echo "dual_log_enable=NO"
        echo "log_ftp_protocol=NO"
        # The container log is a pipe, which cannot be locked like a log file.
        echo "no_log_lock=YES"
        echo "vsftpd_log_file=/proc/1/fd/1"
        echo "use_localtime=YES"
        if tls_available; then
            echo
            echo "# FTPS (explicit TLS on port 21)"
            echo "ssl_enable=YES"
            echo "rsa_cert_file=$FTP_TLS_CERT"
            echo "rsa_private_key_file=$FTP_TLS_KEY"
            echo "allow_anon_ssl=NO"
            echo "force_local_logins_ssl=$tls_force"
            echo "force_local_data_ssl=$tls_force"
            echo "require_ssl_reuse=NO"
            echo "ssl_sslv2=NO"
            echo "ssl_sslv3=NO"
            echo "ssl_ciphers=HIGH"
        fi
    } >"$target"
}

group_name_for() {
    awk -F: -v gid="$1" '$3 == gid { print $1; exit }' /etc/group
}

setup_account() {
    group="$(group_name_for "$FTP_GID")"
    if [ -z "$group" ]; then
        group=ftpupload
        addgroup -g "$FTP_GID" "$group"
    fi
    if id "$FTP_USER" >/dev/null 2>&1; then
        if [ "$(id -u "$FTP_USER")" != "$FTP_UID" ] || [ "$(id -g "$FTP_USER")" != "$FTP_GID" ]; then
            deluser "$FTP_USER"
        fi
    fi
    if ! id "$FTP_USER" >/dev/null 2>&1; then
        adduser -D -H -h "$UPLOAD_DIR" -s /sbin/nologin -u "$FTP_UID" -G "$group" "$FTP_USER" ||
            fail "Konto $FTP_USER mit UID $FTP_UID kann nicht angelegt werden (UID schon vergeben?)"
    fi
    # printf is a shell builtin: the password never shows up in the process list.
    if ! printf '%s:%s\n' "$FTP_USER" "$FTP_PASSWORD" | chpasswd -c sha512 >/dev/null 2>&1; then
        printf '%s:%s\n' "$FTP_USER" "$FTP_PASSWORD" | chpasswd >/dev/null ||
            fail "Passwort für $FTP_USER kann nicht gesetzt werden"
    fi
    printf '%s\n' "$FTP_USER" >"$USER_LIST"
}

prepare_upload_dir() {
    [ -d "$UPLOAD_DIR" ] || fail "$UPLOAD_DIR fehlt - den Eingangsordner eingang/quellen/ftp dort einbinden"
    if [ "$(stat -c %u "$UPLOAD_DIR")" = "0" ]; then
        # Created by Docker as root: hand it to the upload account (top level only).
        chown "$FTP_UID:$FTP_GID" "$UPLOAD_DIR"
    fi
}

if [ "${1:-}" = "--print-config" ]; then
    validate
    write_config /dev/stdout
    exit 0
fi

validate
read_password
prepare_upload_dir
setup_account
mkdir -p "$(dirname "$CONFIG")"
write_config "$CONFIG"
unset FTP_PASSWORD FTP_PASSWORD_FILE

tls_state=aus
if tls_available; then
    if is_yes "$FTP_TLS_REQUIRED"; then tls_state=Pflicht; else tls_state=optional; fi
fi
log "Konto $FTP_USER (UID $FTP_UID), Upload nach $UPLOAD_DIR, passive Ports $FTP_PASV_MIN_PORT-$FTP_PASV_MAX_PORT, Adresse ${FTP_PASV_ADDRESS:-automatisch}, FTPS $tls_state"
exec vsftpd "$CONFIG"
